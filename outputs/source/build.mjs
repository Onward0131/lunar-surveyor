import {build} from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {VEHICLES,VEHICLE_CATEGORIES} from './vehicle-catalog.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
process.chdir(root);
for(const vehicle of VEHICLES)if(vehicle.url&&!fs.existsSync('outputs/'+vehicle.url.replace('./','')))throw new Error(`Missing model: ${vehicle.id}`);
const options=Object.entries(VEHICLE_CATEGORIES).map(([key,label])=>`      <optgroup label="${label}">\n${VEHICLES.filter(v=>v.category===key).map(v=>`        <option value="${v.id}"${v.id==='perseverance'?' selected':''}>${v.name}</option>`).join('\n')}\n      </optgroup>`).join('\n');
let html=fs.readFileSync('outputs/index.html','utf8');
html=html.replace(/<!-- MODEL_OPTIONS_START -->[\s\S]*?<!-- MODEL_OPTIONS_END -->/,`<!-- MODEL_OPTIONS_START -->\n${options}\n      <!-- MODEL_OPTIONS_END -->`);
fs.writeFileSync('outputs/index.html',html);
fs.mkdirSync('outputs/assets/draco',{recursive:true});
for(const name of ['draco_wasm_wrapper.js','draco_decoder.wasm','draco_decoder.js'])fs.copyFileSync('node_modules/three/examples/jsm/libs/draco/gltf/'+name,'outputs/assets/draco/'+name);
await build({entryPoints:['outputs/source/scene.mjs'],outfile:'outputs/app.js',bundle:true,format:'iife',minify:true,target:'es2022',legalComments:'eof'});
fs.mkdirSync('dist/assets',{recursive:true});
for(const name of ['index.html','app.js'])fs.copyFileSync('outputs/'+name,'dist/'+name);
for(const name of ['gravel_stones_diff_2k.jpg','gravel_stones_nor_gl_2k.jpg','gravel_stones_rough_2k.jpg'])fs.copyFileSync('outputs/assets/'+name,'dist/assets/'+name);
fs.cpSync('outputs/assets/models','dist/assets/models',{recursive:true});
fs.cpSync('outputs/assets/draco','dist/assets/draco',{recursive:true});
fs.copyFileSync('outputs/THIRD-PARTY-LICENSES.txt','dist/THIRD-PARTY-LICENSES.txt');
console.log(`Built ${VEHICLES.length} models with local geometry, textures, and decoders.`);
